●リスト5-5 90%ileのレスポンスタイムを求める
SELECT time_id,
       response_time,
       ROW_NUMBER() OVER (ORDER BY response_time) time_rank
  FROM ResponseTimes
 ORDER BY time_rank;


●リスト5-6 90%ileのレスポンスタイム(PostgreSQLとBiGQueryとOracle)
SELECT PERCENTILE_CONT(0.9) WITHIN GROUP (ORDER BY response_time) AS time_rank
  FROM ResponseTimes;

●リスト5-7 90%ileのレスポンスタイム(SQL Server)
SELECT DISTINCT PERCENTILE_CONT(0.9) WITHIN GROUP (ORDER BY response_time) OVER() AS time_rank
  FROM ResponseTimes;
