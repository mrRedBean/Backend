●リスト3-35 UNIONによるテーブルの相等性チェック
SELECT keycol, COUNT(*)
  FROM (SELECT * FROM Tbl_A
        UNION
        SELECT * FROM Tbl_B)
 GROUP BY keycol
HAVING COUNT(*) >= 2;


